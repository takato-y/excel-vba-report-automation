        ["2026/07/12", "テスト物産", "架空ノートA", "abc", 320, 0],      # 5行目: 数量が数値でない
        ["2026/07/13", "テスト物産", "架空ノートA", 5, 320, 1700],       # 6行目: 金額の不一致
